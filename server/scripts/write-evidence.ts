/**
 * Regenerates docs/TEST_EVIDENCE.md from a real run of the Phase 1 script
 * (fresh in-memory database), plus a real restart check on a temporary SQLite file.
 *
 *   npm run evidence
 */
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { appConfig } from '../src/config.js';
import { createCore } from '../src/core/create-core.js';
import { PHASE1_SCRIPT } from '../src/scenario.js';

const TESTS: Record<number, string> = {
  0: '`scenario.test.ts` › step 0',
  1: '`scenario.test.ts` › step 1; `interpreter.test.ts`',
  2: '`scenario.test.ts` › step 2; `when.test.ts` (Tuesday → Nov 10)',
  3: '`scenario.test.ts` › step 3; `when.test.ts` (Thursday instead)',
  4: '`scenario.test.ts` › step 4; `behaviors.test.ts` (staff status changes)',
  5: '`scenario.test.ts` › step 5',
  6: '`scenario.test.ts` › step 6; `behaviors.test.ts` (clock changes)',
  7: '`scenario.test.ts` › step 7; `behaviors.test.ts` (Aetna → yes)',
  8: '`scenario.test.ts` › step 8; `behaviors.test.ts` (no duplicate refill)',
  9: '`scenario.test.ts` › step 9; `safety.test.ts` (no advice ×5)',
  10: '`scenario.test.ts` › step 10',
  11: '`scenario.test.ts` › step 11; `safety.test.ts` (emergency ×16)',
};

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, '<br>');
const core = createCore({ dbPath: ':memory:', dataDir: appConfig.dataDir, scenarioNow: '2026-11-04T10:00:00' });
const conv = core.messaging.listConversations()[0].id;
const rows: string[] = [];

for (const s of PHASE1_SCRIPT) {
  if (s.from === 'clinic') {
    const m = core.messaging.sendClinicMessage(conv, s.text);
    rows.push(`| ${s.step} | **Clinic** \`${m.id}\`: ${cell(s.text)} | ${cell(s.expected)} | Saved as \`${m.id}\` (author \`clinic_staff\`, \`simulated_sms: true\`). No agent reply. Agent reads it as \`${m.meta.expects?.kind}\` (BP recheck with Dr. Priya Lee). | ${TESTS[s.step]} |`);
    continue;
  }
  const { inbound, reply } = await core.messaging.receivePatientMessage(conv, s.text);
  const handled = (reply.meta.items ?? []).map((i) => `\`${i.kind}${i.request_id ? ` ${i.request_id}` : ''}\``).join(', ');
  const link = inbound.in_reply_to ? ` (matched to \`${inbound.in_reply_to}\`)` : '';
  rows.push(`| ${s.step} | **Alex** \`${inbound.id}\`${link}: ${cell(s.text)} | ${cell(s.expected)} | ${cell(reply.body)}<br><br>Agent: ${handled} | ${TESTS[s.step]} |`);
}

const requests = core.requests.list().map((r) => ({ ...r, events: core.requests.events(r.id) }));
core.close();

// Real restart check: steps 0-5, close, reopen the same SQLite file, compare, continue 6-11.
const dir = mkdtempSync(join(tmpdir(), 'sapling-evidence-'));
const dbPath = join(dir, 'sapling.db');
const a = createCore({ dbPath, dataDir: appConfig.dataDir, scenarioNow: '2026-11-04T10:00:00' });
const c1 = a.messaging.listConversations()[0].id;
for (const s of PHASE1_SCRIPT.filter((x) => x.step <= 5)) {
  if (s.from === 'clinic') a.messaging.sendClinicMessage(c1, s.text);
  else await a.messaging.receivePatientMessage(c1, s.text);
}
const before = JSON.stringify({ ...a.snapshot(), exported_at: null });
a.close();
const b = createCore({ dbPath, dataDir: appConfig.dataDir, scenarioNow: '2026-11-04T10:00:00' });
const after = JSON.stringify({ ...b.snapshot(), exported_at: null });
const cont = await b.messaging.receivePatientMessage(c1, 'is it booked yet?');
const restartRows = [
  `- Records identical after reopening the database: **${before === after ? 'yes' : 'NO'}** (${b.repos.messages.all().length - 2} messages, ${b.requests.list().length} request(s), events and agent runs).`,
  `- First message after the restart, "is it booked yet?", was answered from the persisted request: _${cont.reply.body}_`,
];
b.close();
rmSync(dir, { recursive: true, force: true });

const md = `# Test evidence (Phase 1)

_Generated by \`npm run evidence\` from a real run of the agent (fresh database, scenario clock Wednesday, Nov 4, 2026, 10:00 a.m. Pacific). Every row is also asserted by an automated test (last column); run \`npm test\`._

## Phase 1 step table

| # | Input | Expected behavior (from the brief) | Actual result | Automated test |
|---|---|---|---|---|
${rows.join('\n')}

## Handoff records after step 11

Exactly four requests, all \`pending_staff\`, no duplicates. The appointment request was **updated** in step 3 (revision 2), not re-created. Message ids are the ones in the table above.

\`\`\`json
${JSON.stringify(requests, null, 2)}
\`\`\`

## Persistence across a process restart

${restartRows.join('\n')}

The same check runs in \`test/persistence.test.ts\`, including a restart in the middle of a dialogue (between "yes" and "Tuesday afternoon works"). It was also verified against the real HTTP server: steps 0–5 over HTTP, stop the Node process (confirmed exited, port closed), start a new process on the same SQLite file, compare \`GET /api/export\` (byte-identical), then continue steps 6–11 in the same conversation. To repeat it by hand: stop \`npm start\` with Ctrl+C, start it again, and reload the page.

## Automated test suite

\`npm test\` runs Vitest over \`server/test\`:

| File | What it covers |
|---|---|
| \`scenario.test.ts\` | The step table above, one test per step, plus end-state checks (4 handoffs, no booking claims, no timelines, no questions for known info). |
| \`persistence.test.ts\` | Restart with a SQLite file: identical records, continued conversation, ids keep counting, dialogue resumes mid-flow. |
| \`safety.test.ts\` | 16 emergency phrasings flagged, 13 normal messages not flagged; exact text even with other requests in the same message; no advice for 5 clinical questions; no invented insurance policy; clinic messages never trigger the agent. |
| \`when.test.ts\` | Date resolution against the scenario clock: weekdays, "this"/"next", explicit dates, slots, weekends, federal holidays, past dates, after-hours times, clock changes. |
| \`interpreter.test.ts\` | Intent recognition for every script line and 10 paraphrases. |
| \`requests.test.ts\` | Request-store invariants: always starts \`pending_staff\`, schema-validated details, same-id updates with audit diff, closed requests locked, staff-only status changes. |
| \`failure.test.ts\` | Failure injection: a DB error rolls back the whole turn and the reply says nothing was created; the emergency text survives failures; interpreter crash; bad input; strict per-conversation ordering. |
| \`behaviors.test.ts\` | Duplicates avoided, Aetna follow-up, specific slots, weekend handling, Track A phrasing, cross-conversation updates, staff status relayed, cancel disambiguation, pharmacy changes, holidays, clock as a setting. |
| \`http.e2e.test.ts\` | The NestJS API end to end with supertest: messages, requests, staff updates, validation errors, clock, export and reset. |
| \`evals.test.ts\` | The Phase 2 eval cases (all must pass), determinism, negative controls, and the before/after change. |
| \`spelling.test.ts\` | Typo and shorthand repair; every one of the 1,318 protected real English words stays unchanged; misspelled emergencies still caught. |
| \`phrasing.test.ts\` | Every independently written phrasing set: no missed emergency, no unsafe reply, and the tuned sets stay at full coverage. |

Phase 2 (Track B) evidence: see [EVAL_RESULTS.md](EVAL_RESULTS.md) and [EVALS.md](EVALS.md).
`;

const out = join(appConfig.repoRoot, 'docs', 'TEST_EVIDENCE.md');
writeFileSync(out, md);
console.log(`Wrote ${out}`);
